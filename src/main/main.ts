// One data folder whether run from source or installed (an installed app would otherwise use "Lodestar").
app.setPath('userData', path.join(app.getPath('appData'), 'inbox-pilot'));
const DEMO = process.argv.includes('--demo');
if (DEMO) app.setPath('userData', path.join(app.getPath('userData'), 'demo'));
// Source runs only: a separate data folder for testing first-run setup (`--profile=<folder>`).
const PROFILE = process.argv.find((a) => a.startsWith('--profile='))?.slice(10);
if (PROFILE && !app.isPackaged) app.setPath('userData', path.resolve(PROFILE));
/** Developer mode: DevTools (Ctrl+Shift+I) and logs echoed to the console. On when running from source. */
const DEV = !app.isPackaged || process.argv.includes('--dev');
/** Started by Windows at sign-in: stay in the tray. */
const HIDDEN = process.argv.includes('--hidden');

let win: BrowserWindow | null = null;
let lastAppearance: Settings['appearance'] | undefined;
let tray: Tray | null = null;
let quitting = false;

/** The Lodestar mark (white star over a horizon on blue), generated by scripts/make-icon.mjs and copied to dist/assets. */
function loadIcon(): Electron.NativeImage {
  const file = path.join(__dirname, '..', 'assets', 'icon.png');
  const img = nativeImage.createFromPath(file);
  if (!img.isEmpty()) return img;
  // A missing or unreadable icon would leave an invisible tray icon: use a plain accent square instead.
  log.warn('icon.missing', { file });
  const size = 16;
  const bgra = Buffer.alloc(size * size * 4);
  for (let i = 0; i < bgra.length; i += 4) bgra.set([0xd9, 0x59, 0x2b, 0xff], i); // #2b59d9, in BGRA order
  return nativeImage.createFromBitmap(bgra, { width: size, height: size });
}

function showWindow(): void {
  if (!win) return;
  if (win.isMinimized()) win.restore();
  win.show();
  win.focus();
}

function setThemeSource(appearance: Settings['appearance']): void {
  nativeTheme.themeSource = appearance === 'light' || appearance === 'dark' ? appearance : 'system';
}

/** Native controls and the window background follow Lodestar's theme, so there's no white flash in dark mode. */
function applyNativeTheme(appearance: Settings['appearance']): void {
  setThemeSource(appearance);
  win?.setBackgroundColor(THEME_BG[resolveTheme(appearance, nativeTheme.shouldUseDarkColors)]);
}

function createWindow(icon: Electron.NativeImage, appearance: Settings['appearance']): void {
  // themeSource first, so shouldUseDarkColors reflects the chosen theme for the initial background.
  lastAppearance = appearance;
  setThemeSource(appearance);
  win = new BrowserWindow({
    backgroundColor: THEME_BG[resolveTheme(appearance, nativeTheme.shouldUseDarkColors)],
    width: 1100,
    height: 760,
    minWidth: 760,
    minHeight: 500,
    title: DEMO ? 'Lodestar (demo)' : 'Lodestar',
    icon,
    // Lodestar draws its own title bar (logo, title, minimize/maximize/close) in the page.
    frame: false,
    autoHideMenuBar: true,
    webPreferences: {
      preload: path.join(__dirname, '../preload/preload.js'),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });
  win.loadFile(path.join(__dirname, '../web/renderer/index.html'));
  win.webContents.setWindowOpenHandler(() => ({ action: 'deny' }));
  win.webContents.on('will-navigate', (e) => e.preventDefault());
  if (HIDDEN) win.hide();
  // Crash recovery: if the window's renderer dies, log it and reload instead of leaving a blank window.
  win.webContents.on('render-process-gone', (_e, details) => {
    log.error('renderer.gone', { reason: details.reason, exitCode: details.exitCode });
    if (details.reason !== 'clean-exit') setTimeout(() => win?.reload(), 1000);
  });
  win.on('unresponsive', () => log.warn('window.unresponsive'));
  // The page's maximize button shows maximize or restore to match the window.
  const sendMaximized = () => win?.webContents.send('window-maximized', win.isMaximized());
  win.on('maximize', sendMaximized);
  win.on('unmaximize', sendMaximized);
  win.webContents.on('before-input-event', (e, input) => {
    if (DEV && input.control && input.shift && input.key.toLowerCase() === 'i') {
      win?.webContents.toggleDevTools();
      e.preventDefault();
    }
  });
  // Closing the window keeps the assistant running in the tray.
  win.on('close', (e) => {
    if (!quitting) {
      e.preventDefault();
      win?.hide();
    }
  });
}

function createTray(icon: Electron.NativeImage, engine: Engine): void {
  tray = new Tray(icon.resize({ width: 16, height: 16 }));
  tray.setToolTip('Lodestar');
  tray.setContextMenu(
    Menu.buildFromTemplate([
      { label: 'Open Lodestar', click: showWindow },
      { label: 'Check mail now', click: () => void engine.sync() },
      { type: 'separator' },
      { label: 'Quit', click: () => app.quit() },
    ]),
  );
  tray.on('click', showWindow);
}

function openHttps(url: string): Promise<void> {
  if (!/^https:\/\//.test(url)) throw new Error('Refusing to open a non-https link');
  return shell.openExternal(url);
}

function registerIpc(engine: Engine): void {
  ipcMain.handle('getState', () => engine.state());
  // Title bar buttons drawn by the page. Close goes through the normal close path (hide to tray).
  ipcMain.handle('windowMinimize', () => win?.minimize());
  ipcMain.handle('windowToggleMaximize', () => (win?.isMaximized() ? win.unmaximize() : win?.maximize()));
  ipcMain.handle('windowClose', () => win?.close());
  ipcMain.handle('windowIsMaximized', () => !!win?.isMaximized());
  ipcMain.handle('discover', (_e, email: string) => engine.discover(String(email)));
  ipcMain.handle('connect', (_e, req: ConnectRequest) => {
    if (!['gmail', 'outlook', 'imap'].includes(req?.kind)) throw new Error('Unknown provider');
    return engine.connect(req);
  });
  ipcMain.handle('cancelSignIn', () => cancelAuthorize());
  ipcMain.handle('updateAccount', (_e, id: string, patch: AccountPatch) => engine.updateAccount(String(id), patch));
  ipcMain.handle('removeAccount', (_e, id: string) => engine.removeAccount(String(id)));
  ipcMain.handle('syncNow', () => engine.sync());
  ipcMain.handle('act', (_e, key: string, action: UpdateAction) => engine.act(String(key), action));
  ipcMain.handle('sendReply', (_e, key: string, text: string, send: boolean) =>
    engine.sendReply(String(key), String(text), !!send),
  );
  ipcMain.handle('redraft', (_e, key: string) => engine.redraft(String(key)));
  ipcMain.handle('open', (_e, key: string) => openHttps(engine.webLink(String(key))));
  ipcMain.handle('openUrl', (_e, url: string) => openHttps(String(url)));
  ipcMain.handle('unsubscribe', (_e, accountId: string, sender: string) => engine.unsubscribe(String(accountId), String(sender)));
  ipcMain.handle('briefNow', () => engine.brief());
  ipcMain.handle('correct', (_e, key: string, kind: CorrectionKind, scope: 'once' | 'sender' | 'domain') => {
    if (!['more', 'less', 'junk'].includes(kind) || !['once', 'sender', 'domain'].includes(scope)) throw new Error('Invalid correction');
    return engine.correct(String(key), kind, scope);
  });
  ipcMain.handle('doneMany', (_e, keys: string[]) => engine.doneMany(Array.isArray(keys) ? keys.filter((k) => typeof k === 'string') : []));
  ipcMain.handle('dismissSuggestion', (_e, s: Parameters<Engine['dismissSuggestion']>[0]) => engine.dismissSuggestion(s));
  ipcMain.handle('parseRule', (_e, text: string) => engine.parseRule(String(text ?? '')));
  ipcMain.handle('saveRule', (_e, rule: Parameters<Engine['saveRule']>[0]) => engine.saveRule(rule));
  ipcMain.handle('deleteRule', (_e, id: string) => engine.deleteRule(String(id)));
  ipcMain.handle('approve', (_e, id: string) => engine.approve(String(id)));
  ipcMain.handle('reject', (_e, id: string) => engine.reject(String(id)));
  ipcMain.handle('undo', (_e, id: string) => engine.undo(String(id)));
  ipcMain.handle('previewWhen', (_e, phrase: string) => engine.previewWhen(String(phrase)));
  ipcMain.handle('remind', (_e, target: ReminderTarget, phrase: string) => {
    if (!target || !['update', 'followup', 'commitment', 'item'].includes(target.kind)) throw new Error('Invalid reminder target');
    return engine.remind(target, String(phrase));
  });
  ipcMain.handle('cancelReminder', (_e, id: string) => engine.cancelReminder(String(id)));
  ipcMain.handle('setFollowUp', (_e, id: string, status: FollowUp['status']) => {
    if (!['waiting', 'replied', 'done', 'dismissed'].includes(status)) throw new Error('Invalid status');
    return engine.setFollowUp(String(id), status);
  });
  ipcMain.handle('setCommitment', (_e, id: string, status: Commitment['status']) => {
    if (!['open', 'done', 'dismissed'].includes(status)) throw new Error('Invalid status');
    return engine.setCommitment(String(id), status);
  });
  ipcMain.handle('draftNudge', (_e, id: string) => engine.draftNudge(String(id)));
  ipcMain.handle('search', (_e, q: string) => engine.search(String(q)));
  ipcMain.handle('ask', (_e, q: string) => engine.ask(String(q)));
  ipcMain.handle('enableSemantic', (_e, model: string) => engine.enableSemantic(String(model)));
  ipcMain.handle('testNotification', (_e, channel: string) => {
    if (!['desktop', 'ntfy', 'telegram'].includes(channel)) throw new Error('Unknown channel');
    return engine.testNotification(channel as 'desktop' | 'ntfy' | 'telegram');
  });
  ipcMain.handle('setChannelSecret', (_e, channel: string, secret: string) => {
    if (channel !== 'ntfy' && channel !== 'telegram') throw new Error('Unknown channel');
    return engine.setChannelSecret(channel, String(secret));
  });
  ipcMain.handle('detectTelegramChat', () => engine.detectTelegramChat());
  ipcMain.handle('setItem', (_e, id: string, status: KeyItem['status']) => {
    if (!['open', 'done', 'dismissed'].includes(status)) throw new Error('Invalid status');
    return engine.setItem(String(id), status);
  });
  ipcMain.handle('saveSettings', (_e, patch: Partial<Settings>) => {
    engine.saveSettings(patch);
    applyLoginItem(engine.state().settings);
  });
  ipcMain.handle('getBody', (_e, key: string) => engine.getBody(String(key)));
  const cleanupFilter = (f: { categories?: unknown; olderThanDays?: unknown }) => ({
    categories: Array.isArray(f?.categories) ? (f.categories.filter((c) => typeof c === 'string') as Category[]) : [],
    olderThanDays: Math.max(0, Number(f?.olderThanDays) || 0),
  });
  ipcMain.handle('cleanupPreview', (_e, f) => engine.cleanupPreview(cleanupFilter(f)));
  ipcMain.handle('cleanupRun', (_e, f) => engine.cleanupRun(cleanupFilter(f)));
  ipcMain.handle('undoMany', (_e, ids: string[]) => engine.undoMany(Array.isArray(ids) ? ids.filter((x) => typeof x === 'string') : []));
  ipcMain.handle('aiStatus', () => engine.aiStatus());
  ipcMain.handle('aiInstallOllama', () => engine.aiInstallOllama());
  ipcMain.handle('aiStartOllama', () => engine.aiStartOllama());
  ipcMain.handle('aiPullModel', () => engine.aiPullModel());
  ipcMain.handle('learnStyle', () => engine.learnStyle());
  ipcMain.handle('forgetStyle', () => engine.forgetStyle());
  ipcMain.handle('snooze', (_e, key: string, choice: string) => engine.snooze(String(key), String(choice ?? '')));
  ipcMain.handle('previewSnooze', (_e, choice: string) => engine.previewSnooze(String(choice ?? '')));
  ipcMain.handle('freeTimes', (_e, key: string) => engine.freeTimes(String(key)));
  ipcMain.handle('replyOptions', (_e, key: string) => engine.replyOptions(String(key)));
  ipcMain.handle('checkForUpdates', () => engine.checkForUpdates());
  ipcMain.handle('openFolder', (_e, which: string) => shell.openPath(which === 'logs' ? logsDir() : app.getPath('userData')).then(() => undefined));
  ipcMain.handle('dismissNotice', () => engine.dismissNotice());
  ipcMain.handle('listModels', () => engine.listModels());
}

/** Launch at login is only offered by the installed app (from source it would register electron.exe). */
function applyLoginItem(settings: Settings): void {
  if (!app.isPackaged || DEMO) return;
  app.setLoginItemSettings({ openAtLogin: settings.launchAtLogin, args: ['--hidden'] });
}

if (!app.requestSingleInstanceLock()) {
  app.quit();
} else {
  app.on('second-instance', showWindow);
  // Keep running through unexpected errors; they're logged for troubleshooting.
  process.on('uncaughtException', (e) => log.error('uncaught', { error: e }));
  process.on('unhandledRejection', (e) => log.error('unhandled_rejection', { error: e }));
  app.on('child-process-gone', (_e, d) => log.warn('child.gone', { type: d.type, reason: d.reason }));

  app.whenReady().then(async () => {
    // Windows takes the taskbar icon from the Start menu shortcut with this ID. Dev runs get their own ID so a
    // shortcut to node_modules' electron.exe can never claim the installed app's icon.
    app.setAppUserModelId(app.isPackaged ? 'com.inboxpilot.app' : 'com.inboxpilot.app.dev');
    initLogger(DEV);
    log.info('app.start', { version: app.getVersion(), packaged: app.isPackaged, demo: DEMO, hidden: HIDDEN });
    await initSecrets();
    const store = await Store.open();
    if (DEMO) seedDemo(store);
    const engine = new Engine(store, DEMO, (f) => {
      if (!Notification.isSupported()) return;
      const n = new Notification({ title: f.title, body: f.body });
      n.on('click', showWindow);
      n.show();
    });
    engine.appInfo = { version: app.getVersion(), packaged: app.isPackaged, devMode: DEV, notice: store.recovered };
    applyLoginItem(store.data.settings);
    const icon = loadIcon();

    registerIpc(engine);
    createWindow(icon, store.data.settings.appearance);
    createTray(icon, engine);

    // Coalesce bursts of changes into one push to the renderer.
    let pending: NodeJS.Timeout | undefined;
    engine.on('changed', () => {
      const appearance = store.data.settings.appearance;
      if (appearance !== lastAppearance) {
        lastAppearance = appearance;
        applyNativeTheme(appearance);
      }
      clearTimeout(pending);
      pending = setTimeout(() => win?.webContents.send('state', engine.state()), 100);
    });
    // Every notification (desktop and phone) now goes through engine.notifier.

    // Safe shutdown: wait for pending writes (data and secrets) before exiting.
    let flushed = false;
    app.on('before-quit', (e) => {
      quitting = true;
      if (flushed) return;
      e.preventDefault();
      void Promise.all([store.flush(), flushSecrets()]).finally(() => {
        flushed = true;
        log.info('app.quit');
        app.quit();
      });
    });
    // Windows sign-out or shutdown: save immediately.
    win?.on('session-end', () => void store.flush());

    engine.start();
    // Update check on launch and daily, when a feed is configured.
    const checkUpdates = () => {
      const u = store.data.settings.updates;
      if (u.check && u.feedUrl && !DEMO) void engine.checkForUpdates().catch(() => {});
    };
    setTimeout(checkUpdates, 30_000);
    setInterval(checkUpdates, 24 * 3_600_000);
  });
  // Stay alive in the tray when the window is closed.
  app.on('window-all-closed', () => {});
}
